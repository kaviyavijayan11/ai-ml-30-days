class students:
  def __init__(self,name,mark):
    self.name=name
    self.mark=mark

  def get_grade(self):
    if self.mark>=90:
      return "A+"
    elif self.mark>=75:
      return "A"
    elif self.mark>=65:
      return "B"
    else:
      return "F"

  def display(self):
    grade=self.get_grade()
    print (f"{self.name}| Marks:{self.mark}|Grade:{grade}")

s1 = students("Ravi", 85)
s2 = students("Priya", 92)
s3 = students("Karthik", 45)

s1.display()
s2.display()
s3.display()

class BankAccount:
  def __init__(self,owner,balance=0):
    self.owner=owner
    self.balance=balance
    self.transaction=[]
  def deposit(self,amount):
    if amount<=0:
      return "Amount is invalid"
    self.balance+=amount
    self.transaction.append(f"Deposited :+{amount}")
    return f"Deposited Rs.{amount}"

  def withdraw(self,amount):
    if amount>=self.balance:
      return "Insuffient balance"
    if amount<=0:
      return "Amount is invalid"
    self.balance-=amount
    self.transaction.append(f"Withdraw :-{amount}")
    return f"Withdrawn Rs.{amount}"

  def show_balance(self):
    print(f"\n{self.owner}'s account")
    print(f"balance:Rs.{self.balance}")
    print("Transaction")
    for t in self.transaction:
      print(f" {t}")

acc=BankAccount("Ravi",1000)
print(acc.deposit(500))
print(acc.withdraw(200))
print(acc.withdraw(2000))
print(acc.deposit(-100))
acc.show_balance()

class Product:
    def __init__(self, name, price, quantity):
        self.name=name
        self.price=price
        self.quantity=quantity

    def total_cost(self):
        return self.price * self.quantity

    def apply_discount(self, percent):
        discount=(self.price * percent) / 100
        self.price=self.price-discount
        return self.price
    def display(self):
        print(f"{self.name} | Price: {self.price} | Qty: {self.quantity} | Total: {self.total_cost()}")

p1 = Product("Laptop", 50000, 2)
p2 = Product("Phone", 15000, 3)

p1.display()
p1.apply_discount(10)
p1.display()

p2.display()
p2.apply_discount(20)
p2.display()

