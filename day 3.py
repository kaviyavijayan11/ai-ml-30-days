def analyze(marks):
  total=len(marks)
  passed=[m for m in marks if m >=60]
  failed=[m for m in marks if m < 60]
  average=sum(marks)/total
  highest=max(marks)
  lowest=min(marks)

  return total,len(passed),len(failed),round(average,2),highest,lowest

marks = [45, 82, 31, 76, 55, 91, 48, 63, 88, 72]

